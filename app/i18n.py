def tr(language: str, key: str, **values: object) -> str:
    locale = language if language in TEXT else "en"
    return TEXT[locale][key].format(**values)


def programme_content(program, language: str) -> tuple[str, list[str], list[tuple[str, str]]]:
    if language == "en":
        return program.description, [item.value for item in program.requirements], [(item.name, item.description) for item in program.documents]
    translations = PROGRAM_TRANSLATIONS.get(f"{program.university.short_name}_ru") if language == "ru" else PROGRAM_TRANSLATIONS.get(program.university.short_name, {}).get(language)
    if not translations:
        return program.description, [item.value for item in program.requirements], [(item.name, item.description) for item in program.documents]
    return (
        translations["description"],
        translations["requirements"],
        translations["documents"],
    )


